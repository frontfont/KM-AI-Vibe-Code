#!/usr/bin/env python3
"""Build hub/data/projects.js from a registry file and each project's kabac.yaml.

Usage:
    python scripts/build_hub_data.py [registry.yaml] [output.js]

Defaults to the demo registry (hub/demo-registry.yaml) so the prototype works
out of the box. Each registry entry must point to a local `kabac_file`;
fetching kabac.yaml from remote repos is a later step.

The output is a JS file (not JSON) so the site also opens straight from disk.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))
from validate_kabac import SCHEMA_PATH, compute_tier, validate  # noqa: E402
from jsonschema import Draft202012Validator  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent


def main(argv: list[str]) -> int:
    registry_path = Path(argv[0]) if argv else ROOT / "hub" / "demo-registry.yaml"
    out_path = Path(argv[1]) if len(argv) > 1 else ROOT / "hub" / "data" / "projects.js"

    registry = yaml.safe_load(registry_path.read_text(encoding="utf-8")) or {}
    validator = Draft202012Validator(json.loads(SCHEMA_PATH.read_text(encoding="utf-8")))

    projects, failed = [], False
    for entry in registry.get("projects", []):
        kabac_file = ROOT / entry["kabac_file"]
        errors, kabac = validate(kabac_file, validator)
        if errors:
            failed = True
            print(f"❌ {entry.get('slug')}: {kabac_file}")
            for e in errors:
                print(f"   - {e}")
            continue
        audit = dict(entry.get("audit", {}))
        audit["tier"] = compute_tier(kabac["reuse"])  # always derived, never trusted from registry
        projects.append({
            "slug": entry["slug"],
            "version": entry.get("version", "0.1.0"),
            "downloads": entry.get("downloads", 0),
            "cover": entry.get("cover"),
            "audit": audit,
            "kabac": kabac,
        })
        print(f"✅ {entry['slug']}")

    payload = json.dumps({"demo": "demo" in registry_path.name, "projects": projects},
                         ensure_ascii=False, indent=2, default=str)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(
        "// Generated by scripts/build_hub_data.py — do not edit by hand.\n"
        f"window.HUB_DATA = {payload};\n",
        encoding="utf-8",
    )
    print(f"→ {out_path.relative_to(ROOT)} ({len(projects)} projects)")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
